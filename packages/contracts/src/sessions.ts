import { z } from 'zod';
import { AttendanceStatus, IsoDateTime, listQueryOf, pageOf, strictObject, Uuid } from './primitives';

export const CreateSessionRequest = strictObject({
  teamId: Uuid,
  startsAt: IsoDateTime,
  endsAt: IsoDateTime,
  location: z.string().max(200).nullable().default(null),
}).meta({ id: 'CreateSessionRequest' });
export type CreateSessionRequest = z.infer<typeof CreateSessionRequest>;

export const SessionResponse = z
  .object({
    id: Uuid,
    academyId: Uuid,
    teamId: Uuid,
    startsAt: IsoDateTime,
    endsAt: IsoDateTime,
    location: z.string().nullable(),
  })
  .meta({ id: 'SessionResponse' });
export type SessionResponse = z.infer<typeof SessionResponse>;

/**
 * Newest first by default: a coach opening the list wants this week's sessions.
 *
 * `from` and `to` bound `startsAt` as the half-open interval [from, to), the convention
 * every period in this system uses. There is no `q`: a session has no name to search,
 * and a parameter that filtered nothing would be accepted in silence.
 */
export const SessionListQuery = listQueryOf(['startsAt'], '-startsAt')
  .omit({ q: true })
  .extend({
    teamId: Uuid.optional(),
    from: IsoDateTime.optional(),
    to: IsoDateTime.optional(),
  });
export type SessionListQuery = z.infer<typeof SessionListQuery>;

export const SessionPage = pageOf(SessionResponse).meta({ id: 'SessionPage' });
export type SessionPage = z.infer<typeof SessionPage>;

/**
 * Attendance is recorded as PARTICIPATION: a fact about who took part, carrying the team
 * context as it was at that moment. It is never recomputed from current membership, which
 * is what makes historical reports stable across transfers.
 *
 * clientRecordId is generated by the client (phone, possibly offline). It is what makes
 * a retried or late-syncing submission safe to replay: the same id inserts nothing.
 */
export const RecordAttendanceEntry = strictObject({
  clientRecordId: Uuid,
  athleteId: Uuid,
  status: AttendanceStatus,
  note: z.string().max(500).nullable().default(null),
}).meta({ id: 'RecordAttendanceEntry' });
export type RecordAttendanceEntry = z.infer<typeof RecordAttendanceEntry>;

export const RecordAttendanceRequest = strictObject({
  entries: z.array(RecordAttendanceEntry).min(1).max(200),
}).meta({ id: 'RecordAttendanceRequest' });
export type RecordAttendanceRequest = z.infer<typeof RecordAttendanceRequest>;

export const ParticipationResponse = z
  .object({
    id: Uuid,
    academyId: Uuid,
    sessionId: Uuid,
    athleteId: Uuid,
    teamIdAtTime: Uuid,
    status: AttendanceStatus,
    note: z.string().nullable(),
    recordedAt: IsoDateTime,
  })
  .meta({ id: 'ParticipationResponse' });
export type ParticipationResponse = z.infer<typeof ParticipationResponse>;

/** Not paginated: a register is one session's entries, at most one per athlete on the team. */
export const RegisterResponse = z.array(ParticipationResponse);
export type RegisterResponse = z.infer<typeof RegisterResponse>;
