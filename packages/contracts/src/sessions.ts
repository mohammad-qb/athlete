import { z } from 'zod';
import { AttendanceStatus, IsoDateTime, Uuid } from './primitives';

export const CreateSessionRequest = z.object({
  teamId: Uuid,
  startsAt: IsoDateTime,
  endsAt: IsoDateTime,
  location: z.string().max(200).nullable().default(null),
});
export type CreateSessionRequest = z.infer<typeof CreateSessionRequest>;

export const SessionResponse = z.object({
  id: Uuid,
  academyId: Uuid,
  teamId: Uuid,
  startsAt: IsoDateTime,
  endsAt: IsoDateTime,
  location: z.string().nullable(),
});
export type SessionResponse = z.infer<typeof SessionResponse>;

/**
 * Attendance is recorded as PARTICIPATION: a fact about who took part, carrying the team
 * context as it was at that moment. It is never recomputed from current membership, which
 * is what makes historical reports stable across transfers.
 *
 * clientRecordId is generated by the client (phone, possibly offline). Together with the
 * Idempotency-Key header it makes a retried or late-syncing submission safe to replay.
 */
export const RecordAttendanceEntry = z.object({
  clientRecordId: Uuid,
  athleteId: Uuid,
  status: AttendanceStatus,
  note: z.string().max(500).nullable().default(null),
});
export type RecordAttendanceEntry = z.infer<typeof RecordAttendanceEntry>;

export const RecordAttendanceRequest = z.object({
  entries: z.array(RecordAttendanceEntry).min(1).max(200),
});
export type RecordAttendanceRequest = z.infer<typeof RecordAttendanceRequest>;

export const ParticipationResponse = z.object({
  id: Uuid,
  academyId: Uuid,
  sessionId: Uuid,
  athleteId: Uuid,
  teamIdAtTime: Uuid,
  status: AttendanceStatus,
  note: z.string().nullable(),
  recordedAt: IsoDateTime,
});
export type ParticipationResponse = z.infer<typeof ParticipationResponse>;
